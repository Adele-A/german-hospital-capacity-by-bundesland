"""Stage 5 — self-contained Plotly HTML preview (reports/dashboard_preview.html).

Cross-platform stand-in for the Power BI dashboard: map + ranking + trends + Berlin–Brandenburg,
in one file with Plotly.js inlined (no network needed to view).
"""

from __future__ import annotations

import json

import duckdb
import plotly.express as px
import plotly.graph_objects as go

from etl.paths import DASHBOARD_GEO_DIR, REPORTS_DIR

ANCHOR_NOTE = (
    "Independent portfolio project. Data: Statistisches Bundesamt (Destatis), statistic 23111 "
    '(dl-de/by-2-0); boundaries: BKG VG2500. "Fälle" (cases) ≠ unique patients, counted at the '
    "hospital's location. Per-100k: numerator and denominator summed before dividing. Population "
    "has a Zensus-2022 series break."
)


def _geojson() -> dict:
    return json.loads((DASHBOARD_GEO_DIR / "bundeslaender.geojson").read_text(encoding="utf-8"))


def build_html(con: duckdb.DuckDBPyConnection, year: int = 2024) -> str:
    states = (
        con.cursor()
        .execute(
            "SELECT w.*, d.name_en FROM fact_indicators_wide w "
            "JOIN dim_bundesland d USING (ags_code) WHERE w.ags_code <> 'DG'"
        )
        .df()
    )
    cur = states[states["year"] == year].sort_values("beds_per_100k")

    gj = _geojson()
    fig_map = px.choropleth(
        cur,
        geojson=gj,
        locations="ags_code",
        featureidkey="properties.ags_code",
        color="beds_per_100k",
        color_continuous_scale="YlGnBu",
        hover_name="name_en",
        hover_data={"beds_per_100k": ":.0f", "ags_code": False},
        labels={"beds_per_100k": "Beds/100k"},
    )
    fig_map.update_geos(fitbounds="locations", visible=False)
    fig_map.update_layout(
        title=f"Hospital beds per 100,000 inhabitants, {year}", margin=dict(l=0, r=0, t=40, b=0)
    )

    fig_rank = px.bar(
        cur,
        x="beds_per_100k",
        y="name_en",
        orientation="h",
        labels={"beds_per_100k": "Beds per 100,000", "name_en": ""},
        title=f"Ranking — beds per 100k, {year}",
        color_discrete_sequence=["#2a6f97"],
    )
    fig_rank.update_layout(margin=dict(l=0, r=0, t=40, b=0))

    fig_tr = px.line(
        states.sort_values(["ags_code", "year"]),
        x="year",
        y="beds_per_100k",
        color="name_en",
        markers=True,
        title="Beds per 100k over time",
        labels={"beds_per_100k": "Beds per 100,000", "year": "Year", "name_en": "Bundesland"},
    )
    fig_tr.update_layout(margin=dict(l=0, r=0, t=40, b=0))
    fig_tr.update_xaxes(tickmode="array", tickvals=sorted(states["year"].unique()))

    bb = states[states["ags_code"].isin(["11", "12"])].sort_values("year")
    fig_bb = go.Figure()
    for ags, name in (("11", "Berlin"), ("12", "Brandenburg")):
        sub = bb[bb["ags_code"] == ags]
        fig_bb.add_bar(x=sub["year"], y=sub["cases_per_100k"], name=name)
    fig_bb.update_layout(
        barmode="group",
        title="Berlin vs Brandenburg — cases per 100k",
        xaxis_title="Year",
        yaxis_title="Cases per 100,000",
        xaxis=dict(tickmode="array", tickvals=sorted(bb["year"].unique())),
        margin=dict(l=0, r=0, t=40, b=0),
    )

    REPORTS_DIR.mkdir(parents=True, exist_ok=True)
    out = REPORTS_DIR / "dashboard_preview.html"
    blocks = []
    for i, fig in enumerate((fig_map, fig_rank, fig_tr, fig_bb)):
        blocks.append(
            fig.to_html(
                full_html=False,
                include_plotlyjs=("inline" if i == 0 else False),
                div_id=f"fig{i}",  # fixed ids -> deterministic HTML across runs
            )
        )
    html = f"""<!doctype html>
<html lang="en"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>German hospital capacity by Bundesland — preview</title>
<style>
 body{{font-family:system-ui,Arial,sans-serif;max-width:1000px;margin:1.5rem auto;
  padding:0 1rem;color:#1d2a35}}
 h1{{font-size:1.5rem}}
 .note{{font-size:.85rem;color:#51606b;border-left:3px solid #2a6f97;
  padding:.4rem .8rem;background:#f4f8fb}}
 .fig{{margin:1.2rem 0;border:1px solid #e4ebf0;border-radius:8px;padding:.5rem}}
 footer{{font-size:.8rem;color:#70808c;margin-top:2rem}}
</style></head><body>
<h1>German Hospital System by Bundesland — capacity & utilisation</h1>
<p class="note">{ANCHOR_NOTE}</p>
<div class="fig">{blocks[0]}</div>
<div class="fig">{blocks[1]}</div>
<div class="fig">{blocks[2]}</div>
<div class="fig">{blocks[3]}</div>
<footer>Preview generated by <code>python run_etl.py</code>. The Power BI dashboard (data model +
DAX in <code>dashboard/</code>) is built separately; screenshots are added when ready.</footer>
</body></html>"""
    out.write_text(html, encoding="utf-8")
    return str(out)
